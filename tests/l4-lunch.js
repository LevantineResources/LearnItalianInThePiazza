const path = require('path'), fs = require('fs');
const GAME = 'file://' + path.resolve(__dirname, '../dist/index.html');
const SHOTS = path.resolve(__dirname, 'shots'); fs.mkdirSync(SHOTS, { recursive: true });
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const errs = [];
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await p.goto(GAME);
  await p.fill('#nameInput', 'Sam'); await p.click('#btnJump4'); await p.waitForTimeout(2800);
  const obj = async () => console.log('  [objective] ' + await p.textContent('#objective'));
  await obj();
  await p.screenshot({ path: SHOTS + '/40-cafe.png' });
  const clickWorld = async (x, y) => { const r = await p.$eval('#cv', c => { const b = c.getBoundingClientRect(); return { l: b.left, t: b.top, w: b.width, h: b.height }; }); await p.mouse.click(r.l + x / 960 * r.w, r.t + y / 600 * r.h); };
  const talkTo = async (x, y) => { await clickWorld(x, y); await p.waitForSelector('#dialog:not([hidden])', { timeout: 10000 }); await p.waitForTimeout(900); };
  const tiles = async (sel, words) => { for (const w of words) await p.click(`${sel} .tile:not(.used) >> text="${w}"`); };
  const lines = async () => p.$$eval('.line', ls => ls.map(l => l.innerText.replace(/\s+/g, ' ').replace(/ EN$/,'').trim()));
  let seen = 0;
  const check = (label, ok) => console.log(`   ${label} complete: ${!!ok}`);
  const NUMWORDS = /\b(uno?|due|tre|quattro|cinque|sei|sette|otto|nove|dieci|undici|dodici|tredici|quattordici|quindici|sedici|venti|ventuno|trenta|trentuno|quaranta|cinquanta|sessanta|settanta|ottanta|novanta)\b/i;
  const dump = async (tag) => { const L = await lines(); const hint = await p.$eval('#hint', h => h.hidden ? '' : h.innerText.replace(/\s+/g,' ')); console.log(`   ${tag ? tag + ' ' : ''}` + L.slice(seen).join('  →  ') + (hint ? '   [' + hint + ']' : '')); seen = L.length; };
  const say = async (labels, wait = 1600) => { for (const w of labels) await p.click(`#bank .tile >> text="${w}"`); await p.click('#btnSay'); await p.waitForTimeout(wait); await dump(); };
  const pick = async (i, wait = 1400) => { await p.waitForSelector('#choices:not([hidden]) .btn.english', { timeout: 6000 }); const opts = await p.$$eval('#choices .btn', bs => bs.map(b => b.textContent)); console.log('     options:', opts.join(' | ')); await p.click(`#choices .btn.english >> nth=${i}`); await p.waitForTimeout(wait); await dump('     →'); };
  console.log('DAVIDE (fail)'); await talkTo(506, 364);
  await p.waitForSelector('#choices button.primary', { timeout: 9000 }); await dump();
  await p.click('#choices button.primary'); await p.waitForSelector('#modal:not([hidden])'); await obj();
  await p.waitForTimeout(200); await p.$eval('.sheet-body', el => el.scrollTop = 1250);
  await p.screenshot({ path: SHOTS + '/41-handbook4.png' });
  check('L4 handbook shows the total in digits', (await p.textContent('.sheet-body')).includes('Sono 31,50 euro'));
  await p.click('[data-tab=practice]');
  await p.click('[data-opt="1"]'); await p.click('#pxNext');
  await p.click('[data-opt="1"]'); await p.click('#pxNext');
  await p.click('[data-opt="0"]'); await p.click('#pxNext');
  await tiles('#pxBank', ['scusi', 'avete', 'il tiramisù']); await p.click('#pxCheck'); await p.click('#pxNext');
  await tiles('#pxBank', ['per lui', "un'acqua frizzante", 'per favore']); await p.click('#pxCheck'); await p.click('#pxNext');
  await p.click('[data-opt="0"]'); await p.click('#pxNext');
  await p.click('[data-opt="0"]'); await p.click('#pxNext');
  await p.click('#pxGo'); await obj();
  console.log('DAVIDE (order)'); seen = 0; await talkTo(506, 364); await p.waitForTimeout(800); await dump();
  console.log('   bank groups:', await p.$$eval('#bank .bank-label', ls => ls.map(l => l.textContent)));
  await say(['Per lui', 'il risotto ai funghi']);
  await say(['Scusi', 'Avete', 'la pizza'], 2000); await pick(0);
  await say(['Io', 'non', 'posso', 'mangiare', 'la carne']);
  await say(['Lui', 'non', 'posso', 'mangiare', 'la carne']);
  await say(['Lui', 'è', 'vegetariano'], 2000); await pick(1, 900); await pick(0);
  await p.screenshot({ path: SHOTS + '/42-prompt.png' });
  await say(['vorrei', 'il risotto ai funghi'], 2400);
  await say(['Lui', 'vorrebbe', 'il risotto ai funghi'], 2000); await pick(0);
  await say(['Per me', 'la lasagna']);
  await say(['il tiramisù']);
  await say(['Per lui', "un'acqua frizzante", 'e', 'Per me', 'un bicchiere di vino rosso'], 5200);
  await p.screenshot({ path: SHOTS + '/43-served.png' });
  await say(['Il conto', 'per favore'], 2000);
  { const L = await lines(), bill = L.find(l => l.includes('Ecco il conto')) || '';
    check('the bill is in digits', /Ecco il conto\. Sono \d+(,\d\d)? euro\./.test(bill) && !NUMWORDS.test(bill.replace(/^\S+/, '').replace(/Ecco il conto\./, '')));
    await p.waitForSelector('#choices:not([hidden]) .btn.english', { timeout: 6000 });
    const opts = await p.$$eval('#choices .btn', bs => bs.map(b => b.textContent));
    const m = bill.match(/Sono (\d+)(?:,(\d\d))? euro/);
    check('the price prompt offers the bill total', m && opts[1] === `€${m[1]}.${m[2] || '00'}`); }
  await pick(1, 1200); await pick(0);
  await say(['Grazie'], 1500);
  await p.click('#choices button.primary'); await p.waitForTimeout(700);
  await obj();
  console.log('   L4 complete:', await p.isVisible('#modal'), await p.textContent('.sheet h2'));
  await p.screenshot({ path: SHOTS + '/44-complete4.png' });
  console.log('errors:', errs.length ? errs : 'none');
  await b.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
