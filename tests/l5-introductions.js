const path = require('path'), fs = require('fs');
const GAME = 'file://' + path.resolve(__dirname, '../dist/index.html');
const SHOTS = path.resolve(__dirname, 'shots'); fs.mkdirSync(SHOTS, { recursive: true });
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const errs = [];
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await p.goto(GAME);
  await p.fill('#nameInput', 'Sam'); await p.click('#btnJump5'); await p.waitForTimeout(2800);
  const obj = async () => console.log('  [objective] ' + await p.textContent('#objective'));
  await obj();
  await p.keyboard.press('p'); await p.click('#reply1'); await p.waitForTimeout(200); await p.click('.phone-top [data-close]'); await obj();
  await p.screenshot({ path: SHOTS + '/50-piazza-mark.png' });
  const clickWorld = async (x, y) => { const r = await p.$eval('#cv', c => { const b = c.getBoundingClientRect(); return { l: b.left, t: b.top, w: b.width, h: b.height }; }); await p.mouse.click(r.l + x / 960 * r.w, r.t + y / 600 * r.h); };
  const talkTo = async (x, y) => { await clickWorld(x, y); await p.waitForSelector('#dialog:not([hidden])', { timeout: 12000 }); await p.waitForTimeout(1200); };
  const tiles = async (words) => { for (const w of words) await p.click(`#pxBank .tile:not(.used) >> text="${w}"`); };
  const lines = async () => p.$$eval('.line', ls => ls.map(l => l.innerText.replace(/\s+/g, ' ').replace(/ EN$/,'').trim()));
  let seen = 0;
  const dump = async () => { const L = await lines(); const hint = await p.$eval('#hint', h => h.hidden ? '' : h.innerText.replace(/\s+/g,' ')); console.log('   ' + L.slice(seen).join('  →  ') + (hint ? '   [' + hint + ']' : '')); seen = L.length; };
  const say = async (labels, wait = 1800) => { for (const w of labels) await p.click(`#bank .tile >> text="${w}"`); await p.click('#btnSay'); await p.waitForTimeout(wait); await dump(); };
  const leave = async () => { await p.click('#dlgClose'); await p.waitForTimeout(400); seen = 0; };
  console.log('PAOLO + MARK'); await talkTo(590, 432); await p.waitForSelector('#builder:not([hidden])', { timeout: 8000 }); await dump();
  console.log('   bank:', (await p.$$eval('#bank .bank-label', ls => ls.map(l => l.textContent))).join(', '));
  await say(['Ciao', 'Paolo', "Dov'è", 'la statua di Gattamelata'], 7000);
  await p.waitForSelector('#choices:not([hidden]) button.primary', { timeout: 6000 }); await p.click('#choices button.primary');
  await p.waitForTimeout(1500); await dump();
  await p.click('#choices button.primary'); await p.waitForSelector('#modal:not([hidden])'); await obj();
  await p.waitForTimeout(200); await p.$eval('.sheet-body', el => el.scrollTop = 1500);
  await p.screenshot({ path: SHOTS + '/51-handbook5.png' });
  await p.click('[data-tab=practice]');
  for (const st of [['o',0],['o',1],['t',['Le presento','il mio amico','Mark']],['o',0],['o',0],['o',0],['t',['scusi','questa è','la statua di Gattamelata']]]){
    if (st[0] === 'o') await p.click(`[data-opt="${st[1]}"]`); else { await tiles(st[1]); await p.click('#pxCheck'); }
    await p.click('#pxNext');
  }
  await p.click('#pxGo'); await obj();
  console.log('PAOLO (introduce)'); await talkTo(590, 432); await dump();
  await say(['Questa è', 'la mia amica', 'Mark']);
  await say(['Paolo', 'Questo è', 'il mio amico', 'Mark'], 2600);
  await say(['È inglese', 'Non parla italiano'], 2000);
  await leave(); await obj();
  console.log('ENZO'); await talkTo(845, 144); await dump();
  await say(['Ti presento', 'Mark'], 2400);
  await leave();
  console.log('GIULIA'); await talkTo(760, 290); await dump();
  await say(['Ti presento', 'il mio amico', 'Mark'], 2400);
  await leave(); await obj();
  await p.screenshot({ path: SHOTS + '/52-follow.png' });
  await p.keyboard.press('m'); await p.waitForSelector('.mapsvg');
  const node = async (c, r) => p.click(`[data-node="${c},${r}"]`);
  await node(2,3); await node(2,2); await p.click('#mCheck'); console.log('   map 1:', await p.textContent('.mapstatus'));
  await p.click('#mClear'); for (const [c, r] of [[2,3],[3,3],[4,3],[5,3],[5,4]]) await node(c, r); await p.click('#mCheck'); console.log('   map 2:', await p.textContent('.mapstatus'));
  await p.click('#mUndo'); for (const [c, r] of [[5,2],[5,1],[5,0]]) await node(c, r); await p.click('#mCheck'); console.log('   map 3:', await p.textContent('.mapstatus'));
  await p.screenshot({ path: SHOTS + '/53-map5.png' });
  await p.click('[data-go="santo"]'); await p.waitForTimeout(2800); await obj();
  await p.screenshot({ path: SHOTS + '/54-santo.png' });
  console.log('LUCIA'); await talkTo(476, 376); await dump();
  await say(['Scusi', 'Questa è', 'la statua di Gattamelata'], 2200);
  await say(['Mi chiamo Sam'], 2200);
  await say(['Le presento', 'il mio amico', 'Mark'], 4500);
  await p.waitForSelector('#choices:not([hidden]) .btn.english', { timeout: 6000 });
  console.log('     options:', (await p.$$eval('#choices .btn', bs => bs.map(b => b.textContent))).join(' | '));
  await p.click('#choices .btn.english >> nth=0'); await p.waitForTimeout(1800); await dump();
  await say(['Grazie mille'], 1800);
  await p.click('#choices button.primary'); await p.waitForTimeout(700); await obj();
  console.log('   L5 complete:', await p.isVisible('#modal'), await p.textContent('.sheet h2'));
  await p.screenshot({ path: SHOTS + '/55-complete5.png' });
  console.log('errors:', errs.length ? errs : 'none');
  await b.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
