#!/usr/bin/env node
/*
 * Builds dist/index.html: one self-contained file (HTML + CSS + JS) that runs offline
 * and is what gets published.
 *
 * The JS files are concatenated, in the order below, inside a single
 * (() => { 'use strict'; ... })() wrapper. They are plain scripts, not modules:
 * everything shares one scope, so a function in one file can call a function in another.
 * Order matters only for top-level const/let that are *used at load time*
 * (e.g. NPCS must exist before content/npcs.js pushes into it).
 *
 * Lesson folders are picked up automatically, sorted by name: src/lessons/NN-name/content.js goes in the
 * content slot, every other .js file in the folder goes in the lesson-logic slot.
 *
 * Art (the museum's paintings and statues, Lesson 11) is NOT inlined: the build copies the files the game uses
 * (assets/art/<file>, <thumb>, manifest.json) to <out dir>/art/, and the game loads them by relative URL ('art/…').
 * The manifest's data is embedded in the bundle as `const ART = {…}` (no fetch(): file:// pages can't fetch).
 * assets/art is made by scripts/prepare-art.py from assets/art-originals.
 *
 * Usage: node scripts/build.js [--watch]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'dist', 'index.html');
const ART_DIR = path.join(ROOT, 'assets', 'art');

/* the art manifest, as a generated source file (const ART = { rooms, note, works }) */
function artManifest(){
  const m = JSON.parse(fs.readFileSync(path.join(ART_DIR, 'manifest.json'), 'utf8'));
  return { rel:'(generated from assets/art/manifest.json)', code:`/* generated by scripts/build.js from assets/art/manifest.json: the museum's works (world/galleria.js) */\nconst ART = ${JSON.stringify(m)};` };
}
/* copy the art the game uses to <outDir>/art/ (only files that changed) */
function copyArt(outDir){
  const m = JSON.parse(fs.readFileSync(path.join(ART_DIR, 'manifest.json'), 'utf8'));
  const dest = path.join(outDir, 'art'); fs.mkdirSync(dest, { recursive: true });
  const files = ['manifest.json', ...m.works.flatMap(w => [w.file, w.thumb])];
  let copied = 0;
  for (const f of files){
    const a = path.join(ART_DIR, f), b = path.join(dest, f), sa = fs.statSync(a);
    if (fs.existsSync(b)){ const sb = fs.statSync(b); if (sb.size === sa.size && sb.mtimeMs >= sa.mtimeMs) continue; }
    fs.copyFileSync(a, b); copied++;
  }
  return { files: files.length, copied };
}

/* lesson folders: src/lessons/NN-name, plus any extra folders passed to build() (used by tests) */
function lessonFolders(extra = []){
  const dir = path.join(SRC, 'lessons');
  const own = fs.readdirSync(dir).filter(d => /^\d\d-/.test(d) && fs.statSync(path.join(dir, d)).isDirectory())
    .map(d => ({ name: d, abs: path.join(dir, d), rel: `lessons/${d}` }));
  return [...own, ...extra.map(e => ({ name: e.name, abs: path.resolve(e.dir), rel: `lessons/${e.name}` }))]
    .sort((a, b) => a.name.localeCompare(b.name));
}
const lessonContent = extra => lessonFolders(extra).filter(f => fs.existsSync(path.join(f.abs, 'content.js')))
  .map(f => ({ rel: `${f.rel}/content.js`, abs: path.join(f.abs, 'content.js') }));
const lessonLogic = extra => lessonFolders(extra).flatMap(f => fs.readdirSync(f.abs)
  .filter(x => x.endsWith('.js') && x !== 'content.js').sort().map(x => ({ rel: `${f.rel}/${x}`, abs: path.join(f.abs, x) })));
/* quest folders: src/quests/NN-name (Lesson 12 on, engine/quests.js), picked up like lesson folders: every .js file in a
   folder, in name order, goes in the quest slot, right after the lessons' logic (a quest can use any lesson's functions) */
function questFolders(extra = []){
  const dir = path.join(SRC, 'quests');
  const own = fs.existsSync(dir) ? fs.readdirSync(dir).filter(d => /^\d\d-/.test(d) && fs.statSync(path.join(dir, d)).isDirectory())
    .map(d => ({ name: d, abs: path.join(dir, d), rel: `quests/${d}` })) : [];
  return [...own, ...extra.map(e => ({ name: e.name, abs: path.resolve(e.dir), rel: `quests/${e.name}` }))].sort((a, b) => a.name.localeCompare(b.name));
}
const questLogic = extra => questFolders(extra).flatMap(f => fs.readdirSync(f.abs)
  .filter(x => x.endsWith('.js')).sort().map(x => ({ rel: `${f.rel}/${x}`, abs: path.join(f.abs, x) })));

