/* opts.out: output path (default dist/index.html); opts.extraLessons: [{ name:'07-x', dir }]; opts.extraQuests: the same, for quests */
function build(opts = {}){
  const files = order(opts.extraLessons || [], opts.extraQuests || []);
  const seen = new Set(files.map(f => f.rel));
  // every .js under src must be in the build, so nothing is silently left out
  const all = [];
  (function walk(d){ for (const f of fs.readdirSync(d)){ const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (f.endsWith('.js')) all.push(path.relative(SRC, p).split(path.sep).join('/')); } })(SRC);
  const stray = all.filter(f => !seen.has(f));
  if (stray.length) throw new Error('Not in the build order (add them to scripts/build.js): ' + stray.join(', '));

  const js = files.map(f => {
    if (f.code) return `/* ===== ${f.rel} ===== */\n${f.code}\n`;
    if (!fs.existsSync(f.abs)) throw new Error('Missing source file: ' + f.rel);
    return `/* ===== ${f.rel} ===== */\n` + fs.readFileSync(f.abs, 'utf8').replace(/\s+$/, '') + '\n';
  }).join('\n');
  const css = fs.readFileSync(path.join(SRC, 'styles.css'), 'utf8').replace(/\s+$/, '');
  const tpl = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8');
  if (!tpl.includes('<!-- @styles -->') || !tpl.includes('<!-- @script -->')) throw new Error('src/index.html needs <!-- @styles --> and <!-- @script --> placeholders');
  const html = tpl
    .replace('<!-- @styles -->', () => css)
    .replace('<!-- @script -->', () => `(() => {\n'use strict';\n\n${js}\n})();`);

  // catch syntax errors at build time rather than in the browser
  try { new Function(`(() => {\n'use strict';\n\n${js}\n})`); }
  catch (e) { throw new Error('JavaScript syntax error in the bundle: ' + e.message); }

  const out = opts.out || OUT;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  const art = copyArt(path.dirname(out));
  return { files: files.length, bytes: html.length, art };
}

if (require.main === module){
  const run = () => { try { const r = build(); console.log(`built dist/index.html  (${r.files} files, ${(r.bytes / 1024).toFixed(0)} KB) + dist/art/ (${r.art.files} files, ${r.art.copied} copied)`); } catch (e) { console.error('BUILD FAILED: ' + e.message); if (!process.argv.includes('--watch')) process.exit(1); } };
  run();
  if (process.argv.includes('--watch')){
    let t = null;
    fs.watch(SRC, { recursive: true }, () => { clearTimeout(t); t = setTimeout(run, 150); });
    console.log('watching src/ ...');
  }
}
module.exports = { build, order, copyArt };
