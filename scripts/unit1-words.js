#!/usr/bin/env node
/*
 * Unit 1's words, for Venezia (Unit 2 assumes Unit 1 is finished: its dictionary, and later Studio, start with them).
 * Run by scripts/build.js before Venezia's bundle (units/venezia/unit.json "generate"); also `node scripts/unit1-words.js`.
 *
 * How: Padova's own bundle (the engine + units/padova, exactly as `build padova` concatenates it) is evaluated in a Node `vm`
 * context whose window / document are inert stand-ins (every property is a callable no-op; no timers, no frames), so
 * nothing runs but the scripts' top level: the lessons, quests and cast register themselves as in the browser. Then
 * window.__unitExport() (engine/ui/handbook.js) puts the save in Padova's end-of-unit state (UNIT.finishedState(),
 * units/padova/early/handbook.js) and returns the dictionary the player sees then (dictSections()), and the set phrases.
 * Nothing of Padova's code or scenes goes into Venezia: only this data, written to units/venezia/generated/unit1-words.js
 * (only when it changed) as `const UNIT1 = { from, title, sections, setPhrases }`.
 */
const vm = require('vm');
const fs = require('fs');
const path = require('path');

const OUT = path.resolve(__dirname, '..', 'units', 'venezia', 'generated', 'unit1-words.js');

/* an inert DOM: any property is another stand-in, calling or constructing one returns one, it is '' or 0 as a primitive,
   an empty iterable, and assignments are remembered (so code that sets and reads back a property sees its value) */
function inert(){
  const store = {};
  return new Proxy(function(){}, {
    get(t, k){
      if (k === Symbol.toPrimitive) return hint => hint === 'number' ? 0 : '';
      if (k === Symbol.iterator) return function*(){};
      if (k === 'toJSON') return undefined;
      if (k === 'then') return () => {};
      if (!(k in store)) store[k] = inert();
      return store[k];
    },
    set(t, k, v){ store[k] = v; return true; },
    has(){ return false; },
    apply(){ return inert(); },
    construct(){ return inert(); },
  });
}
function sandbox(){
  const noop = () => 0;
  const win = {
    console:{ log:noop, warn:noop, error:noop, info:noop }, Math, JSON, Date, Object, Array, Set, Map, WeakMap, WeakSet, String, Number, Boolean, RegExp,
    Error, TypeError, Promise, Symbol, Proxy, Reflect, Intl, parseInt, parseFloat, isNaN, isFinite, encodeURIComponent, decodeURIComponent,
    Uint8Array, Uint8ClampedArray, Float32Array, Int32Array,
    setTimeout:noop, clearTimeout:noop, setInterval:noop, clearInterval:noop, requestAnimationFrame:noop, cancelAnimationFrame:noop,
    document:inert(), navigator:inert(), speechSynthesis:inert(), location:{ search:'', hash:'', href:'' },
    localStorage:{ getItem:() => null, setItem:noop, removeItem:noop },
    matchMedia:() => ({ matches:false, addEventListener:noop, addListener:noop }), performance:{ now:() => 0 }, getComputedStyle:() => inert(),
    devicePixelRatio:1, innerWidth:1280, innerHeight:800, addEventListener:noop, removeEventListener:noop,
  };
  for (const k of ['Image', 'Audio', 'SpeechSynthesisUtterance', 'ResizeObserver', 'MutationObserver', 'IntersectionObserver', 'Path2D', 'DOMParser',
    'HTMLElement', 'Event', 'KeyboardEvent', 'CustomEvent', 'AudioContext', 'webkitAudioContext']) win[k] = function(){ return inert(); };
  win.window = win; win.self = win; win.globalThis = win;
  return win;
}

/* the data, from Padova's sources as they are now */
function unit1(){
  const { bundle } = require('./build.js');
  const { js } = bundle('padova');
  const win = sandbox();
  vm.runInContext(`(() => {\n'use strict';\n${js}\n})();`, vm.createContext(win), { filename:'padova-bundle.js' });
  if (typeof win.__unitExport !== 'function') throw new Error("Padova's bundle has no window.__unitExport (engine/ui/handbook.js)");
  const x = win.__unitExport();
  const sections = x.dictionary
    .map(sec => ({ title:sec.title, blocks:sec.blocks.map(b => ({ note:b.note || null, entries:b.entries.map(e => e.num !== undefined ? { num:e.num }
      : Object.fromEntries(Object.entries({ w:e.w, en:e.en, key:e.key, say:e.say && e.say !== e.w ? e.say : undefined }).filter(([, v]) => v !== undefined && v !== null))) })) }))
    .filter(sec => sec.blocks.some(b => b.entries.length));
  return { from:x.unit, title:x.title, sections, setPhrases:x.setPhrases };
}

function generate(o = {}){
  const data = unit1();
  const words = data.sections.reduce((a, s) => a + s.blocks.reduce((b, k) => b + k.entries.length, 0), 0);
  const body = `/* generated by scripts/unit1-words.js from units/padova (its dictionary at the end of Unit 1): do not edit.
   ${data.sections.length} sections, ${words} entries, ${data.setPhrases.length} set phrases. Venezia (units/venezia/unit.js) shows them in its
   dictionary from the start and counts them as known words. */
const UNIT1 = ${JSON.stringify(data, null, 1).replace(/\n\s*/g, ' ')};
`.replace(/\{ "title"/g, '\n  { "title"');
  fs.mkdirSync(path.dirname(OUT), { recursive:true });
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (old !== body) fs.writeFileSync(OUT, body);
  if (!o.quiet && require.main === module) console.log(`${path.relative(process.cwd(), OUT)}: ${data.sections.length} sections, ${words} entries${old === body ? ' (unchanged)' : ''}`);
  return { sections:data.sections.length, words, changed:old !== body };
}

module.exports = { generate, unit1, sandbox };
if (require.main === module) generate();
