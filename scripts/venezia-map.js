#!/usr/bin/env node
/*
 * The designer's San Marco map sketch, for Venezia's walkable city. Run by scripts/build.js before Venezia's bundle
 * (units/venezia/unit.json "generate"); also `node scripts/venezia-map.js`.
 *
 * Reads docs/data/venezia-sanmarco-map.json (the snapshot of the "Piazza · Venezia map sketch" artifact: a 96 × 64 grid of
 * ~10 m cells, its legend, points of interest and areas) and writes units/venezia/generated/sanmarco-map.js,
 * `const SKETCH = { source, w, h, legend, rows, pois, zones }` (only when it changed; committed, so a diff shows when the
 * designer's map changes). Nothing is interpreted here: units/venezia/world/tiles.js turns the sketch into tile maps when the
 * game loads. To take a new export of the sketch, replace the JSON and build.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.resolve(__dirname, '..', 'docs', 'data', 'venezia-sanmarco-map.json');
const OUT = path.resolve(__dirname, '..', 'units', 'venezia', 'generated', 'sanmarco-map.js');

function generate(opts = {}){
  const d = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  if (!Array.isArray(d.rows) || d.rows.length !== d.h || d.rows.some(r => r.length !== d.w)) throw new Error(`${path.relative(process.cwd(), SRC)}: rows must be ${d.h} strings of ${d.w} cells`);
  const known = new Set(Object.keys(d.legend));
  d.rows.forEach((r, y) => [...r].forEach((ch, x) => { if (!known.has(ch)) throw new Error(`venezia map: unknown cell '${ch}' at ${x},${y}`); }));
  const data = { source:d.source, w:d.w, h:d.h, legend:d.legend, note:d.note, rows:d.rows, pois:d.pois, zones:d.zones };
  const code = `/* generated by scripts/venezia-map.js from docs/data/venezia-sanmarco-map.json: the designer's map sketch of San Marco
   (1 cell ≈ 10 m, north up). Do not edit: export the sketch again and build. units/venezia/world/tiles.js reads it. */
const SKETCH = {
  source:${JSON.stringify(data.source)},
  w:${data.w}, h:${data.h}, legend:${JSON.stringify(data.legend)},
  note:${JSON.stringify(data.note)},
  rows:[
${data.rows.map(r => '    ' + JSON.stringify(r)).join(',\n')},
  ],
  pois:[
${data.pois.map(p => '    ' + JSON.stringify(p)).join(',\n')},
  ],
  zones:[
${data.zones.map(z => '    ' + JSON.stringify(z)).join(',\n')},
  ],
};
`;
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (old !== code){ fs.mkdirSync(path.dirname(OUT), { recursive:true }); fs.writeFileSync(OUT, code); if (!opts.quiet) console.log('wrote ' + path.relative(process.cwd(), OUT)); }
  return { changed:old !== code };
}
module.exports = { generate };
if (require.main === module) generate();
